#!/usr/bin/env python3
"""Regenerate ``src/pypdfcraft/_bindings.py`` from a freshly built engine library.

    python scripts/gen_bindings.py path/to/libpdfcraft_android.so

The UniFFI bindings are tied to the exact engine build (they embed per-function checksums that are
verified when the library is loaded), so run this whenever ``rust/`` changes.  The bindgen used is
the workspace's own ``pdfcraft-android-bindgen`` crate (same locked uniffi version as the library);
set ``UNIFFI_BINDGEN=/path/to/uniffi-bindgen`` to use a prebuilt binary instead.
"""
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUST = ROOT / "rust"
OUT = ROOT / "src" / "pypdfcraft" / "_bindings.py"

HEADER = '''# AUTO-GENERATED by scripts/gen_bindings.py from rust/apps/pdfcraft-android (UniFFI). DO NOT EDIT.
# Regenerate with:  python scripts/gen_bindings.py <path-to-built-library>
# The native library is located and loaded by pypdfcraft._loader.
'''

LOADER_HOOK = '''def _uniffi_load_indirect():
    from ._loader import load_native
    return load_native()


'''


def main(argv):
    if len(argv) != 2:
        sys.exit(__doc__)
    lib = Path(argv[1]).resolve()
    if not lib.is_file():
        sys.exit(f"library not found: {lib}")
    bindgen = os.environ.get("UNIFFI_BINDGEN")
    cmd = [bindgen] if bindgen else ["cargo", "run", "--release", "-q", "-p", "pdfcraft-android-bindgen", "--"]
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(cmd + ["generate", "--library", str(lib), "--crate", "pdfcraft_android",
                              "--language", "python", "--no-format", "--out-dir", tmp],
                       cwd=RUST, check=True)
        src = (Path(tmp) / "pdfcraft_android.py").read_text(encoding="utf-8")
    a = src.index("def _uniffi_load_indirect():")
    b = src.index("def _uniffi_check_contract_api_version")
    src = HEADER + src[:a] + LOADER_HOOK + src[b:]
    src = re.sub(r"[ \t]+\n", "\n", src)
    OUT.write_text(src, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(src.splitlines())} lines)")


if __name__ == "__main__":
    main(sys.argv)
