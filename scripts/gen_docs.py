#!/usr/bin/env python3
"""Generate the reference pages in ``docs/``: api.md, tools.md, coverage.md (no native library needed)."""
import inspect
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import pypdfcraft as pdf  # noqa: E402
from pypdfcraft import api, features, speech  # noqa: E402

DOCS = ROOT / "docs"
CATALOG = json.loads((ROOT / "src/pypdfcraft/data/tools_catalog.json").read_text(encoding="utf-8"))["tools"]


def sig(fn):
    try:
        return str(inspect.signature(fn))
    except (TypeError, ValueError):
        return "(...)"


def func_page():
    out = ["# Function reference", "",
           "<!-- generated by scripts/gen_docs.py - do not edit -->", "",
           "All functions take file **paths**; `out` is always optional (a new `<name>_<what>.pdf` is created next to the "
           "source, never overwriting; `inplace=True` overwrites). Pages, lines and image numbers are **1-based**. "
           "They return a `Result` (`r.out` = file or folder written).", ""]
    groups = {**api.CATALOG, **{f"{k} (more)": v for k, v in features.CATALOG.items()}, **speech.CATALOG}
    for cat, names in groups.items():
        out += [f"## {cat}", ""]
        for n in names:
            fn = getattr(api, n, None) or getattr(features, n, None) or getattr(speech, n, None) or getattr(pdf, n, None)
            if not callable(fn):
                continue
            out += [f"### `{n}`", "", "```python", f"pypdfcraft.{n}{sig(fn)}", "```", "",
                    inspect.getdoc(fn) or "", ""]
    (DOCS / "api.md").write_text("\n".join(out), encoding="utf-8")


def tools_page():
    out = ["# Engine tool reference", "",
           "<!-- generated by scripts/gen_docs.py - do not edit -->", "",
           f"The engine exposes **{len(CATALOG)} tools** (the same table the PdfCraft CLI / MCP server use). "
           "Each is available three ways:", "",
           "```python",
           'pdf.<tool>("in.pdf", ..., out=None)          # one call, path based   (pypdfcraft.oneshot)',
           'pdf.apply("in.pdf", "<tool>", ..., out=None)  # same, by name',
           'doc.<tool>(...)  /  doc.<group>.<name>(...)   # on an open Document (document id filled in)',
           "```", "", "Pages are **1-based**.", ""]
    for t in sorted(CATALOG, key=lambda x: x["name"]):
        s = t["input_schema"]
        req = set(s.get("required", []))
        out += [f"## `{t['name']}`", "", f"**{t['title']}**" + ("  _(read-only)_" if t["read_only"] else ""), "",
                t["description"].strip(), ""]
        props = s.get("properties", {})
        if props:
            out += ["| argument | type | |", "|---|---|---|"]
            for k, v in sorted(props.items(), key=lambda kv: (kv[0] not in req, kv[0])):
                ty = "enum: " + ", ".join(map(str, v["enum"])) if v.get("enum") else str(v.get("type", "any"))
                d = (v.get("description") or "").replace("\n", " ").replace("|", "\\|")
                out.append(f"| `{k}`{' *' if k in req else ''} | {ty} | {d} |")
            out.append("")
    (DOCS / "tools.md").write_text("\n".join(out), encoding="utf-8")


def coverage_page():
    src = "".join((ROOT / "src/pypdfcraft" / f).read_text(encoding="utf-8") for f in ("api.py", "features.py", "editing.py"))
    used = {}
    for m in re.finditer(r'(?:tool|apply|run_tool|_tool)\(\s*(?:src,\s*)?"([a-z0-9_]+)"', src):
        used.setdefault(m.group(1), set())
    # find the enclosing public function of each reference
    for fn_name in list(api.__all__) + list(features.__all__):
        fn = getattr(api, fn_name, None) or getattr(features, fn_name, None)
        if not callable(fn) or isinstance(fn, type):
            continue
        try:
            body = inspect.getsource(fn)
        except (OSError, TypeError):
            continue
        for tn in re.findall(r'"([a-z0-9_]+)"', body):
            if any(tn == t["name"] for t in CATALOG):
                used.setdefault(tn, set()).add(fn_name)
    rows = ["# Feature coverage", "",
            "<!-- generated by scripts/gen_docs.py - do not edit -->", "",
            f"Every one of the engine's {len(CATALOG)} tools is reachable from Python. "
            "`curated` = has a hand-written, friendly function; all others are available through the generated "
            "`pypdfcraft.<tool>(...)` one-shot function and `doc.<tool>(...)`.", "",
            "| engine tool | title | curated function(s) | one-shot |", "|---|---|---|---|"]
    n_cur = 0
    for t in sorted(CATALOG, key=lambda x: x["name"]):
        cur = sorted(used.get(t["name"], []))
        n_cur += bool(cur)
        one = f"`pypdfcraft.{t['name']}`" if t["name"] not in {"doc_open", "doc_close", "doc_list", "doc_save"} else "`pypdfcraft.open()` / `Document.save()`"
        rows.append(f"| `{t['name']}` | {t['title']} | {', '.join(f'`{c}`' for c in cur) or '-'} | {one} |")
    rows += ["", f"**{n_cur} of {len(CATALOG)}** tools also have a curated friendly function.", "",
             "## Native (UniFFI) API", "",
             "| engine method | Python |", "|---|---|"]
    native = [("MobileSession.open / close / documents / document", "`pypdfcraft.open()`, `Document.close()`, `pypdfcraft.documents()`"),
              ("render_page", "`Document.render()`, `pypdfcraft.render()`"),
              ("page_plain_text / reading_blocks / find_in_page", "`Document.text()`, `.blocks()`, `.search()`; reading blocks drive `read_aloud()`, `to_audio()`, `ReadAloud`"),
              ("outline / links / comments / attachments / widgets", "`Document.outline()`, `.links()`, `.comments()`, `.attachments()`, `.widgets()`"),
              ("save_attachment / save_sound", "`Document.save_attachment()`, `.save_sound()`"),
              ("signer_certificate", "`Document.signer_certificate()`"),
              ("word_at / text_of / glyph_count / nearest_glyph / glyph_rect / text_rects", "`Document.word_at()`, `.text_of()`, `.glyph_count()`, `.nearest_glyph()`, `.glyph_rect()`, `.text_rects()`"),
              ("execute / tools", "`pypdfcraft.tool()`, `pypdfcraft.tools()`, `pypdfcraft.apply()`"),
              ("release_memory", "`pypdfcraft.release_memory()`"),
              ("file_thumbnail / digital_id_info / engine_version / init_logging", "`pypdfcraft.thumbnail()`, `.digital_id_info()`, `.engine_version()`, `.init_logging()`")]
    rows += [f"| {a} | {b} |" for a, b in native]
    (DOCS / "coverage.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    return n_cur


def index_page():
    """docs/index.md = README with repo-relative links turned into GitHub / docs links."""
    s = (ROOT / "README.md").read_text(encoding="utf-8")
    s = s.replace("](docs/", "](")
    base = "https://github.com/FarazAli30/pypdfcraft/blob/main/"
    for f in ("LICENSE-MIT", "NOTICE", "AUTHORS.md", "rust/ATTRIBUTION.md"):
        s = s.replace(f"]({f})", f"]({base}{f})")
    (DOCS / "index.md").write_text(s, encoding="utf-8")


if __name__ == "__main__":
    DOCS.mkdir(exist_ok=True)
    index_page()
    func_page(); tools_page(); n = coverage_page()
    print(f"docs generated; {n}/{len(CATALOG)} tools with curated functions")
