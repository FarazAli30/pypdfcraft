#!/usr/bin/env python3
"""Generate ``src/pypdfcraft/oneshot.py``: one typed, documented, path-based function per engine tool.

    python scripts/gen_oneshot.py            # reads src/pypdfcraft/data/tools_catalog.json

Every tool that works on a document becomes ``tool_name(src, *, <its arguments>, out=None,
inplace=False, password=None)`` and is run through :func:`pypdfcraft.apply`; tools without a document
argument become ``tool_name(*, <its arguments>)`` and run through :func:`pypdfcraft.run_tool`.
"""
import json
import keyword
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "src" / "pypdfcraft" / "data" / "tools_catalog.json"
OUT = ROOT / "src" / "pypdfcraft" / "oneshot.py"

SKIP = {"doc_open", "doc_close", "doc_list", "doc_save"}        # session management: use pypdfcraft.open()
DOC_KEYS = ("doc",)
PY = {"integer": "int", "number": "float", "string": "str", "boolean": "bool", "array": "list", "object": "dict"}


def ann(schema):
    if not isinstance(schema, dict):
        return "Any"
    if schema.get("enum"):
        vals = ", ".join(repr(v) for v in schema["enum"])
        return f"Literal[{vals}]"
    t = schema.get("type")
    if isinstance(t, list):
        t = next((x for x in t if x != "null"), None)
    return PY.get(t, "Any")


def pyname(n):
    return n + "_" if keyword.iskeyword(n) else n


def doc_text(tool, params):
    lines = [f"{tool['title']}  [{tool['name']}]", ""]
    lines += textwrap.wrap(tool["description"].strip().replace("\n", " "), 96) if tool["description"] else []
    if params:
        lines += ["", "Args:"]
        for name, req, schema in params:
            d = (schema.get("description") or "").strip().replace("\n", " ")
            lines += textwrap.wrap(f"{pyname(name)} ({ann(schema)}{'' if req else ', optional'}): {d}",
                                   96, initial_indent="    ", subsequent_indent="        ")
    return "\n".join(lines).replace('"""', "'''").replace("\\", "\\\\")


def render():
    data = json.loads(CATALOG.read_text(encoding="utf-8"))["tools"]
    out = ['"""AUTO-GENERATED by scripts/gen_oneshot.py from the engine\'s tool table. DO NOT EDIT.',
           "",
           "One function per engine tool, path-based (``fn(\"in.pdf\", ...)``): see :func:`pypdfcraft.apply`.",
           '"""',
           "from typing import Any, Literal  # noqa: F401",
           "",
           "from .api import apply, run_tool",
           "from .results import Result  # noqa: F401",
           "",
           "__all__ = []", ""]
    names = []
    for t in sorted(data, key=lambda x: x["name"]):
        n = t["name"]
        if n in SKIP:
            continue
        schema = t["input_schema"]
        props = schema.get("properties", {}) or {}
        req = set(schema.get("required", []))
        has_doc = any(k in props for k in DOC_KEYS)
        params = [(k, k in req, v) for k, v in props.items() if k not in DOC_KEYS]
        params.sort(key=lambda p: (not p[1], p[0]))
        taken = {pyname(k) for k, _, _ in params}
        gen_out = "save_as" if "out" in taken else "out"            # the tool has its own `out`
        gen_pw = "doc_password" if "password" in taken else "password"
        sig = []
        if has_doc:
            sig.append("src")
        sig.append("*")
        for k, r, v in params:
            sig.append(f"{pyname(k)}: {ann(v)}" + ("" if r else " = None"))
        if has_doc:
            sig += [f"{gen_out}=None", "inplace=False", f"{gen_pw}=None"]
        else:
            sig = sig[:] if params else []
            if sig == ["*"]:
                sig = []
        sig_s = ", ".join(sig)
        if sig_s.startswith("*,") and not has_doc:
            pass
        kw = ", ".join(f"{k!r}: {pyname(k)}" for k, _, _ in params)
        body_kw = f"{{k: v for k, v in {{{kw}}}.items() if v is not None}}"
        if has_doc:
            call = (f"return apply(src, {n!r}, out={gen_out}, inplace=inplace, password={gen_pw}, "
                    f"suffix='edited', **{body_kw})")
        else:
            call = f"return run_tool({n!r}, **{body_kw})"
        out.append(f"def {n}({sig_s}) -> Result:")
        out.append('    """' + doc_text(t, params).replace("\n", "\n    ") + '\n    """')
        out.append("    " + call)
        out.append("")
        names.append(n)
    out.append("__all__ = [" + ", ".join(repr(n) for n in names) + "]")
    return "\n".join(out) + "\n", len(names)


def main():
    text, n = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date: run python scripts/gen_oneshot.py")
        print(f"{OUT.relative_to(ROOT)} is up to date ({n} functions)")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {n} functions")


if __name__ == "__main__":
    main()
