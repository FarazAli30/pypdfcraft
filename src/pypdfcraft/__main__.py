"""python -m pypdfcraft <command>

  tools [group]             list every tool (table)
  describe NAME             full documentation of one tool
  run NAME ['{"json":..}']  run a tool headlessly (no document)
  catalog [--json F] [--md F]   dump the complete tool catalogue (share this to get tailored wrappers)
  stubs [--out F]           write a static module with one real, typed function per tool
  diagnose                  check that the engine loads (CPU, library path, OCR models)
  install-models [--apk F]  get the OCR models (download, or extract from the PdfCraft APK)
  read FILE [--pages 1-3] [--rate 1.2] [--voice V] [--save out.wav]   read aloud / write an audio file
  voices                    list the voices of the speech engine
  voices [--engine E]       list the voices of the speech engine
  version                   engine + package version
"""
import argparse
import json
import sys

from . import __version__, _registry, diagnose, engine_version, install_models, session
from .tools import Tool


def _ver():
    try:
        return engine_version()
    except Exception:                      # noqa: BLE001  (e.g. a test double without the native lib)
        return "unknown"


def _cmd_tools(a):
    reg = _registry()
    for n, t in sorted(reg.tools.items()):
        if a.group and not n.startswith(a.group + "_"):
            continue
        print(f"{n:34s}{'ro ' if t.read_only else 'rw '} {t.title}")
    print(f"\n{len(reg.tools)} tools; groups: {', '.join(reg.groups())}")


def _cmd_describe(a):
    print(_registry().lookup(a.name).__doc__)


def _cmd_run(a):
    out = _registry().lookup(a.name)(**(json.loads(a.args) if a.args else {}))
    print(json.dumps(out, indent=2, ensure_ascii=False) if not isinstance(out, str) else out)


def _cmd_catalog(a):
    reg = _registry()
    data = [{"name": t.name, "title": t.title, "description": t.info.description,
             "read_only": t.read_only, "input_schema": t.schema} for t in reg.tools.values()]
    out_json = a.json or "pypdfcraft_tools.json"
    with open(out_json, "w", encoding="utf-8") as f:
        json.dump({"engine_version": _ver(), "tools": data}, f, indent=2, ensure_ascii=False)
    print("wrote", out_json)
    if a.md:
        with open(a.md, "w", encoding="utf-8") as f:
            f.write(f"# pypdfcraft tools (engine {_ver()})\n\n")
            for t in sorted(reg.tools.values(), key=lambda x: x.name):
                f.write(f"## `{t.name}`\n\n```\n{t.__doc__}\n```\n\n")
        print("wrote", a.md)


def _pages(spec):
    if not spec:
        return None
    out = []
    for part in spec.split(","):
        lo, _, hi = part.strip().partition("-")
        out += list(range(int(lo), int(hi or lo) + 1))
    return out


def _cmd_read(a):
    import pypdfcraft as pdf
    kw = dict(pages=_pages(a.pages), rate=a.rate, voice=a.voice, language=a.language, backend=a.backend,
              password=a.password)
    if a.save:
        print(pdf.to_audio(a.file, a.save if a.save != "auto" else None, **kw))
        return
    try:
        r = pdf.read_aloud(a.file, wait=False, on_paragraph=(lambda p: print(f"[p{p.page}] {p.text[:100]}")), **kw)
        r.join()
    except KeyboardInterrupt:
        print("\nstopped")
    finally:
        try:
            r.close()
        except Exception:                               # noqa: BLE001
            pass


def _cmd_voices(a):
    import pypdfcraft as pdf
    for v in pdf.voices(a.backend):
        print(v)


def _cmd_stubs(a):
    reg = _registry()
    lines = ['"""AUTO-GENERATED by `python -m pypdfcraft stubs` - one typed function per engine tool."""',
             "from typing import Any, Literal", "from pypdfcraft import call", "",
             "__all__ = [" + ", ".join(repr(n) for n in sorted(reg.tools)) + "]", ""]
    for n, t in sorted(reg.tools.items()):
        params = t.params
        sig = []
        for p in params:
            ann = p.annotation
            if getattr(ann, "__origin__", None) is not None:        # Literal[...]
                ann_s = repr(ann).replace("typing.", "")
            else:
                ann_s = getattr(ann, "__name__", "Any")
            sig.append(f"{p.py_name}: {ann_s}" + ("" if p.required else f" = {p.default!r}"))
        if t.free_form:
            sig.append("**params: Any")
        kw = "*, " if sig and not t.free_form else ""
        lines.append(f"def {n}({kw}{', '.join(sig)}) -> Any:")
        doc = t.__doc__.replace('"""', "'''").replace("\\", "\\\\")
        lines.append('    """' + doc.replace("\n", "\n    ") + '\n    """')
        mapping = ", ".join(f"{p.name!r}: {p.py_name}" for p in params)
        extra = "**params" if t.free_form else ""
        lines.append(f"    return call({n!r}, **{{k: v for k, v in {{{mapping}{', ' if mapping and extra else ''}"
                     f"{'**params' if extra else ''}}}.items() if v is not None}})")
        lines.append("")
    path = a.out or "pypdfcraft_tools.py"
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {path} ({len(reg.tools)} functions)")


def main(argv=None):
    ap = argparse.ArgumentParser(prog="pypdfcraft", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("tools"); s.add_argument("group", nargs="?"); s.set_defaults(fn=_cmd_tools)
    s = sub.add_parser("describe"); s.add_argument("name"); s.set_defaults(fn=_cmd_describe)
    s = sub.add_parser("run"); s.add_argument("name"); s.add_argument("args", nargs="?"); s.set_defaults(fn=_cmd_run)
    s = sub.add_parser("catalog"); s.add_argument("--json"); s.add_argument("--md"); s.set_defaults(fn=_cmd_catalog)
    s = sub.add_parser("stubs"); s.add_argument("--out"); s.set_defaults(fn=_cmd_stubs)
    s = sub.add_parser("diagnose"); s.set_defaults(fn=lambda a: diagnose())
    s = sub.add_parser("install-models"); s.add_argument("--apk"); s.add_argument("--dest")
    s.set_defaults(fn=lambda a: print("models in", install_models(a.dest, a.apk)))
    s = sub.add_parser("read")
    s.add_argument("file")
    s.add_argument("--pages", help="e.g. 1-3,5")
    s.add_argument("--rate", type=float, default=1.0)
    s.add_argument("--voice")
    s.add_argument("--language")
    s.add_argument("--backend", help="espeak | say | sapi | pyttsx3 | termux | plyer | spd-say")
    s.add_argument("--password")
    s.add_argument("--save", nargs="?", const="auto", help="write an audio file instead of speaking")
    s.set_defaults(fn=_cmd_read)
    s = sub.add_parser("voices"); s.add_argument("--backend"); s.set_defaults(fn=_cmd_voices)
    s = sub.add_parser("version"); s.set_defaults(fn=lambda a: print(f"engine {_ver()}, pypdfcraft {__version__}"))
    a = ap.parse_args(argv)
    a.fn(a)


if __name__ == "__main__":
    main()
